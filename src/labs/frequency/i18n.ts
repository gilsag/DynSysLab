export function locale(lang: Lang) {
  return LANGS.find((l) => l.code === lang)!.locale;
}

export function fmt(x: number, lang: Lang, digits = 3) {
  if (!isFinite(x)) return x > 0 ? '∞' : x < 0 ? '−∞' : '—';
  if (x === 0) return '0';
  const ax = Math.abs(x);
  let s: string;
  if (ax >= 1e5 || ax < 1e-3) s = x.toExponential(digits - 1).replace('e+', 'e');
  else s = new Intl.NumberFormat(locale(lang), { maximumSignificantDigits: digits }).format(x);
  return s.replace('-', '−');
}
